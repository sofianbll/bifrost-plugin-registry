// Run: node docs/design/mockup/check-hermes.cjs
// One scenario check for the pure model embedded in the standalone prototype.
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync(`${__dirname}/hermes-prototype.html`, 'utf8');
const source = html.match(/<script id="catalogue-logic">([\s\S]*?)<\/script>/)[1];
const D = vm.runInNewContext(`${source}; RegistryDemo;`);
const ids = key => Array.from(D.exposed(key, s.groups));
let s = D.initial();
assert.deepEqual(ids(s.draft), ['gpt-demo', 'claude-demo']);
s.draft = D.toggleModel(s.draft, s.groups, 'gemini-demo');
s.draft = D.toggleModel(s.draft, s.groups, 'claude-demo');
assert.deepEqual(ids(s.draft), ['gpt-demo', 'gemini-demo']);
assert.deepEqual(ids(s.keys.witness), ['gpt-demo', 'claude-demo']);
s = D.publish(s);
s = D.publishGroup(s, 'code', ['gpt-demo', 'claude-demo', 'kimi-demo']);
assert.deepEqual(ids(s.keys.hermes), ['gpt-demo', 'gemini-demo', 'kimi-demo']);
assert.deepEqual(ids(s.keys.witness), ['gpt-demo', 'claude-demo', 'kimi-demo']);
assert.throws(() => D.publishGroup(s, 'code', []), /au moins un modèle/);
s.draft.groups.push('favorites');
s.draft = D.toggleModel(s.draft, s.groups, 'gpt-demo');
assert.ok(!ids(s.draft).includes('gpt-demo'), 'Exclusion must win over both groups');
s.draft = D.toggleModel(s.draft, s.groups, 'gpt-demo');
s.draft.naming = 'both';
assert.equal(ids(s.draft).filter(id => id === 'gpt-demo').length, 1);
assert.ok(ids(s.draft).includes('openai/gpt-demo'));
assert.ok(ids(s.draft).includes('opencode/gpt-demo'));
const previousRead = Array.from(s.observed.hermes);
s.readAvailable = false;
s = D.publish(s);
assert.equal(s.readFailed, true);
assert.deepEqual(Array.from(s.observed.hermes), previousRead, 'Failed read must preserve last observation');
assert.equal(s.keys.hermes.naming, 'both', 'Save and read are distinct states');
s.readAvailable = true;
s = D.read(s);
assert.deepEqual(Array.from(s.observed.hermes), ids(s.keys.hermes));
s.draft.groups = []; s.draft.added = []; s.draft.excluded = [];
assert.deepEqual(ids(s.draft), [], 'Empty selection must remain empty');
console.log('OK: local selection, shared inheritance, overlapping groups, names, failed read, empty catalogue.');
